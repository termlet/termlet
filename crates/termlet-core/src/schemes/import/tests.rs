/// 测试用的 16 色（自拟）。
const P: [&str; 16] = [
    "#101010", "#c03030", "#30a030", "#c0a030", "#3060c0", "#a040a0", "#30a0a0", "#c0c0c0",
    "#505050", "#ff5050", "#50ff50", "#ffff50", "#5080ff", "#ff50ff", "#50ffff", "#ffffff",
];
const WT_NAMES: [&str; 8] = [
    "black", "red", "green", "yellow", "blue", "purple", "cyan", "white",
];
const ANSI: [&str; 8] = [
    "black", "red", "green", "yellow", "blue", "magenta", "cyan", "white",
];

fn bright(n: &str) -> String {
    format!("bright{}{}", n[..1].to_uppercase(), &n[1..])
}

fn parse(text: &str, file: &str) -> ParseResult {
    parse_schemes(text, Some(file))
}

fn parse_text(text: &str) -> ParseResult {
    parse_schemes(text, None)
}

fn names(r: &ParseResult) -> Vec<&str> {
    r.schemes.iter().map(|s| s.name.as_str()).collect()
}

fn scheme(
    name: &str,
    foreground: &str,
    background: &str,
    cursor: &str,
    selection: &str,
    ansi: &[&str],
) -> ColorScheme {
    ColorScheme {
        name: name.into(),
        foreground: foreground.into(),
        background: background.into(),
        cursor: cursor.into(),
        selection_background: selection.into(),
        ansi: ansi.iter().map(|c| c.to_string()).collect(),
        ..ColorScheme::default()
    }
}

/// Windows Terminal 的一套配色（JSON 对象）。
fn wt_object(name: &str, extra: &[(&str, &str)]) -> Map<String, Value> {
    let mut o = Map::new();
    o.insert("name".into(), name.into());
    o.insert("foreground".into(), "#DDDDDD".into());
    o.insert("background".into(), "#202020".into());
    o.insert("cursorColor".into(), "#FFCC00".into());
    o.insert("selectionBackground".into(), "#444466".into());
    for (i, n) in WT_NAMES.iter().enumerate() {
        o.insert(n.to_string(), P[i].into());
        o.insert(bright(n), P[i + 8].into());
    }
    for (k, v) in extra {
        o.insert(k.to_string(), (*v).into());
    }
    o
}

fn to_json(o: &Map<String, Value>) -> String {
    Value::Object(o.clone()).to_string()
}

fn rgb(hex: &str) -> String {
    let n = u32::from_str_radix(&hex[1..], 16).unwrap();
    format!("{},{},{}", (n >> 16) & 255, (n >> 8) & 255, n & 255)
}

/// 拼一个 .itermcolors
fn plist(colors: &[(String, String)], space: &str) -> String {
    let dicts: Vec<String> = colors
        .iter()
        .map(|(key, hex)| {
            let n = u32::from_str_radix(&hex[1..], 16).unwrap();
            let c = |v: u32| format!("{:.6}", f64::from(v) / 255.0);
            format!(
                "<key>{key}</key>\n\t<dict>\n\t\t<key>Alpha Component</key><real>1</real>\n\t\t<key>Blue Component</key><real>{}</real>\n\t\t<key>Color Space</key><string>{space}</string>\n\t\t<key>Green Component</key><real>{}</real>\n\t\t<key>Red Component</key><real>{}</real>\n\t</dict>",
                c(n & 255),
                c((n >> 8) & 255),
                c((n >> 16) & 255)
            )
        })
        .collect();
    format!(
        "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<!DOCTYPE plist PUBLIC \"-//Apple//DTD PLIST 1.0//EN\" \"http://www.apple.com/DTDs/PropertyList-1.0.dtd\">\n<plist version=\"1.0\">\n<dict>\n\t{}\n</dict>\n</plist>\n",
        dicts.join("\n\t")
    )
}

fn iterm_colors(suffix: &str) -> Vec<(String, String)> {
    let mut o: Vec<(String, String)> = P
        .iter()
        .enumerate()
        .map(|(i, c)| (format!("Ansi {i} Color{suffix}"), c.to_string()))
        .collect();
    for (k, v) in [
        ("Background Color", "#202020"),
        ("Foreground Color", "#dddddd"),
        ("Cursor Color", "#ffcc00"),
        ("Selection Color", "#444466"),
    ] {
        o.push((format!("{k}{suffix}"), v.to_string()));
    }
    o
}

fn sample() -> ColorScheme {
    scheme("Mine", "#dddddd", "#202020", "#ffcc00", "#444466", &P)
}

