#[test]
fn iterm_binary_plist_file() {
    // 文件字节是二进制 plist 时直接读取
    let mut dict = plist::Dictionary::new();
    for (key, hex) in iterm_colors("") {
        let n = u32::from_str_radix(&hex[1..], 16).unwrap();
        let mut c = plist::Dictionary::new();
        c.insert("Color Space".into(), "sRGB".into());
        c.insert(
            "Red Component".into(),
            (f64::from((n >> 16) & 255) / 255.0).into(),
        );
        c.insert(
            "Green Component".into(),
            (f64::from((n >> 8) & 255) / 255.0).into(),
        );
        c.insert("Blue Component".into(), (f64::from(n & 255) / 255.0).into());
        dict.insert(key, plist::Value::Dictionary(c));
    }
    let mut bytes = Vec::new();
    plist::Value::Dictionary(dict)
        .to_writer_binary(&mut bytes)
        .unwrap();
    let r = parse_scheme_bytes(&bytes, Some("Bin.itermcolors"));
    assert_eq!(r.format, Some(SchemeFormat::Iterm2));
    assert_eq!(
        r.schemes,
        [ColorScheme {
            name: "Bin".into(),
            ..sample()
        }]
    );
    assert_eq!(r.warnings, []);
    // 损坏的二进制 plist：提示重新导出
    let r = parse_scheme_bytes(b"bplist00\x00\x01garbage", Some("x.itermcolors"));
    assert_eq!(r.format, Some(SchemeFormat::Iterm2));
    assert_eq!(r.warnings, [ImportWarning::BinaryPlist]);
}

// ---- Xshell ----

fn xcs() -> String {
    let normal: Vec<String> = ANSI
        .iter()
        .enumerate()
        .map(|(i, n)| format!("{n}={}", &P[i][1..]))
        .collect();
    let bold: Vec<String> = ANSI
        .iter()
        .enumerate()
        .map(|(i, n)| format!("{n}(bold)={}", &P[i + 8][1..]))
        .collect();
    format!(
        "[Names]\nname0=Night\nname1=暗色 Dark\ncount=2\n[Night]\ntext=dddddd\ntext(bold)=ffffff\nbackground=202020\n{}\n{}\n[暗色 Dark]\ntext=c0c0c0\nbackground=000000\nblack=000000\nred=800000\ngreen=008000\nyellow=808000\nblue=000080\nmagenta=800080\ncyan=008080\nwhite=c0c0c0\n",
        normal.join("\n"),
        bold.join("\n")
    )
}

#[test]
fn xshell_several_schemes_bold_is_bright() {
    let r = parse(&xcs(), "mine.xcs");
    assert_eq!(r.format, Some(SchemeFormat::Xshell));
    assert_eq!(names(&r), ["Night", "暗色 Dark"]);
    assert_eq!(r.schemes[0].ansi, P);
    assert_eq!(r.schemes[0].foreground, "#dddddd");
    // 第二套没有 bold 色
    assert_eq!(r.schemes[1].ansi[8..], r.schemes[1].ansi[..8]);
    assert!(r.warnings.contains(&ImportWarning::MissingBright {
        scheme: "暗色 Dark".into(),
        count: 8
    }));
}

#[test]
fn xshell_utf16_le_with_bom_and_crlf() {
    let text = format!("\u{feff}{}", xcs().replace('\n', "\r\n"));
    let bytes: Vec<u8> = text.encode_utf16().flat_map(u16::to_le_bytes).collect();
    let r = parse(&decode_scheme_file(&bytes), "mine.xcs");
    assert_eq!(r.format, Some(SchemeFormat::Xshell));
    assert_eq!(names(&r), ["Night", "暗色 Dark"]);
    // 读文件的入口直接用字节
    let r = parse_scheme_bytes(&bytes, Some("mine.xcs"));
    assert_eq!(names(&r), ["Night", "暗色 Dark"]);
}

