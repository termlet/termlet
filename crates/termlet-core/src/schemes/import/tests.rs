#[test]
fn decode_utf8_with_and_without_bom() {
    let body = "[配色]\ntext=ffffff\n".as_bytes();
    assert_eq!(decode_scheme_file(body), "[配色]\ntext=ffffff\n");
    let with_bom = [&[0xef, 0xbb, 0xbf][..], body].concat();
    assert_eq!(decode_scheme_file(&with_bom), "[配色]\ntext=ffffff\n");
}

#[test]
fn decode_utf16_with_bom() {
    let mut le = vec![0xff, 0xfe];
    le.extend("[A]".bytes().flat_map(|c| [c, 0]));
    le.extend([0x4d, 0x91]);
    assert_eq!(decode_scheme_file(&le), "[A]配");
    let mut be = vec![0xfe, 0xff];
    be.extend("[A]".bytes().flat_map(|c| [0, c]));
    assert_eq!(decode_scheme_file(&be), "[A]");
}

#[test]
fn decode_utf16_le_without_bom() {
    let text = "[Names]\nname0=Night\ncount=1\n";
    let bytes: Vec<u8> = text.bytes().flat_map(|c| [c, 0]).collect();
    assert_eq!(decode_scheme_file(&bytes), text);
    let be: Vec<u8> = text.bytes().flat_map(|c| [0, c]).collect();
    assert_eq!(decode_scheme_file(&be), text);
}

#[test]
fn decode_gbk_when_not_utf8() {
    assert_eq!(
        decode_scheme_file(&[0x5b, 0xc5, 0xe4, 0xc9, 0xab, 0x5d]),
        "[配色]"
    );
}

#[test]
fn decode_empty_file() {
    assert_eq!(decode_scheme_file(&[]), "");
}
