#[test]
fn wt_missing_selection_and_bright() {
    let mut o = wt_object("Partial", &[]);
    for n in WT_NAMES {
        o.remove(&bright(n));
    }
    o.remove("selectionBackground");
    let r = parse_text(&to_json(&o));
    let s = &r.schemes[0];
    assert_eq!(s.ansi[8..], P[..8]);
    // 选区由前景与背景混合（前景占 30%）
    assert_eq!(s.selection_background, "#595959");
    assert_eq!(
        r.warnings,
        [
            ImportWarning::MissingBright {
                scheme: "Partial".into(),
                count: 8
            },
            ImportWarning::MissingSelection {
                scheme: "Partial".into()
            },
        ]
    );
}

