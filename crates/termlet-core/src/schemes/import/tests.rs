/// 别名炸弹：8 层，每层 12 个键都是上一层的别名，叶子是 ~ 或 []（不是字符串），展开后有 12^8 个节点。
fn alias_bomb(leaf: &str, tail: &str) -> String {
    let mut lines = vec!["l0: &l0".to_string(), format!("  a: {leaf}")];
    for level in 1..=8 {
        lines.push(format!("l{level}: &l{level}"));
        for k in 1..=12 {
            lines.push(format!("  k{k}: *l{}", level - 1));
        }
    }
    format!("{}\n{tail}", lines.join("\n"))
}

#[test]
fn yaml_alias_bombs_return_quickly() {
    let inputs = [
        alias_bomb("~", "colors: *l8\n"),
        alias_bomb("[]", "colors: *l8\n"),
        alias_bomb(
            "~",
            "scheme:\n  name: *l8\n  foreground: '#ffffff'\n  background: '#000000'\n  colors: ['#000000', '#ff0000', '#00ff00', '#ffff00', '#0000ff', '#ff00ff', '#00ffff', '#ffffff']\n",
        ),
    ];
    assert!(inputs[0].len() < 1500);
    for text in &inputs {
        assert!(timed(text, Some("bomb.yaml")) < Duration::from_secs(2));
    }
    // Tabby 的配色照常识别（名称不是字符串时用文件名）
    let r = parse(&inputs[2], "bomb.yaml");
    assert_eq!(r.format, Some(SchemeFormat::Tabby));
    assert_eq!(r.schemes[0].name, "bomb");
}

