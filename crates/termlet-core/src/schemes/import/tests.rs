#[test]
fn wt_whole_settings_json() {
    let second = wt_object("Second", &[("purple", "#123456"), ("cursorColor", "oops")]);
    let text = format!(
        r#"// This file was initially generated by Windows Terminal
{{
    "$schema": "https://aka.ms/terminal-profiles-schema",
    "defaultProfile": "{{61c54bbd-c2c6-5271-96e7-009a87ff44bf}}",
    /* 多行
       注释 */
    "profiles": {{ "list": [ {{ "name": "PowerShell", "colorScheme": "First", }}, ], }},
    "schemes": [
        {},
        {},
    ],
}}"#,
        to_json(&wt_object("First", &[])),
        to_json(&second)
    );
    let r = parse(&text, "settings.json");
    assert_eq!(r.format, Some(SchemeFormat::WindowsTerminal));
    assert_eq!(names(&r), ["First", "Second"]);
    assert_eq!(r.schemes[1].ansi[5], "#123456");
    // 光标颜色写法不对：提示并改用前景色
    assert_eq!(r.schemes[1].cursor, "#dddddd");
    assert_eq!(
        r.warnings,
        [
            ImportWarning::InvalidColor {
                scheme: "Second".into(),
                field: ColorField::Cursor,
                value: "oops".into(),
            },
            ImportWarning::MissingCursor {
                scheme: "Second".into()
            },
        ]
    );
}

